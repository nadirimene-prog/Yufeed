    async def process(self, context: AgentContext) -> AgentResult:
        """
        Process a compliance officer request.

        Supported actions:
        - generate_briefing: Generate daily/weekly briefing
        - answer_question: Answer compliance Q&A
        - assess_impact: Assess regulatory impact
        - monitor_risks: Proactive risk monitoring
        """
        action = context.input_data.get("action", "generate_briefing")

        if action == "generate_briefing":
            return await self._generate_briefing(context)
        elif action == "answer_question":
            return await self._answer_question(context)
        elif action == "assess_impact":
            return await self._assess_impact(context)
        elif action == "monitor_risks":
            return await self._monitor_risks(context)
        else:
            return AgentResult(
                agent_type=self.agent_type,
                success=False,
                result=None,
                confidence=0.0,
                reasoning=f"Unknown action: {action}",
                error=f"Unsupported action: {action}",
            )

    async def _generate_briefing(self, context: AgentContext) -> AgentResult:
        """Generate a compliance briefing."""
        logger.info("Generating compliance briefing")

        try:
            # Extract parameters
            lookback_hours = context.input_data.get("lookback_hours", 24)
            briefing_type = context.input_data.get("briefing_type", BriefingType.DAILY)

            # Get operational data (in production, fetch from database)
            alert_stats = context.input_data.get("alert_stats", self._get_demo_alert_stats())
            case_stats = context.input_data.get("case_stats", self._get_demo_case_stats())
            sar_stats = context.input_data.get("sar_stats", self._get_demo_sar_stats())
            transaction_summary = context.input_data.get(
                "transaction_summary", self._get_demo_transaction_summary()
            )
            regulatory_updates = context.input_data.get(
                "regulatory_updates", self._get_demo_regulatory_updates()
            )
            system_health = context.input_data.get("system_health", self._get_demo_system_health())

            # Calculate period
            period_end = utc_now()
            period_start = period_end - timedelta(hours=lookback_hours)

            # Build prompt
            prompt = self.BRIEFING_PROMPT.format(
                period_start=period_start.strftime("%Y-%m-%d %H:%M"),
                period_end=period_end.strftime("%Y-%m-%d %H:%M"),
                alert_stats=self._format_stats(alert_stats),
                case_stats=self._format_stats(case_stats),
                sar_stats=self._format_stats(sar_stats),
                transaction_summary=transaction_summary,
                regulatory_updates=regulatory_updates,
                system_health=self._format_stats(system_health),
            )
            context.input_data["_prompt_version"] = "compliance_officer.briefing.2026-02-25.1"

            # Call Claude
            response = await self.call_claude(prompt, context)

            # Build briefing object
            briefing = self._build_briefing(
                response=response,
                alert_stats=alert_stats,
                case_stats=case_stats,
                sar_stats=sar_stats,
                period_start=period_start,
                period_end=period_end,
                briefing_type=briefing_type,
            )

            return AgentResult(
                agent_type=self.agent_type,
                success=True,
                result=briefing.to_dict(),
                confidence=self.calculate_confidence(response),
                reasoning="Generated comprehensive compliance briefing",
                metadata={
                    "briefing_type": (
                        briefing_type.value
                        if isinstance(briefing_type, BriefingType)
                        else briefing_type
                    ),
                    "period_hours": lookback_hours,
                    "risk_level": response.get("overall_risk_level", "medium"),
                    "compliance_score": response.get("compliance_score", 75),
                },
            )

        except Exception as e:
            logger.error(f"Briefing generation error: {e}")
            return AgentResult(
                agent_type=self.agent_type,
                success=False,
                result=None,
                confidence=0.0,
                reasoning=f"Failed to generate briefing: {str(e)}",
                error=str(e),
            )

    async def _answer_question(self, context: AgentContext) -> AgentResult:
        """Answer a compliance question using RAG."""
        logger.info("Processing compliance question")

        try:
            question = context.input_data.get("question", "")
            conversation_history = context.input_data.get("conversation_history", [])
            regulatory_context = context.input_data.get("regulatory_context", "")

            if not question:
                return AgentResult(
                    agent_type=self.agent_type,
                    success=False,
                    result=None,
                    confidence=0.0,
                    reasoning="No question provided",
                    error="Question is required",
                )

            # If no regulatory context provided, use default EU AML context
            if not regulatory_context:
                regulatory_context = self._get_default_regulatory_context()

            # Format conversation history
            history_text = ""
            if conversation_history:
                for msg in conversation_history[-5:]:  # Last 5 messages
                    role = msg.get("role", "user")
                    content = msg.get("content", "")
                    history_text += f"\n{role.upper()}: {content}"

            # Build prompt
            prompt = self.COMPLIANCE_QA_PROMPT.format(
                regulatory_context=regulatory_context,
                conversation_history=history_text or "No previous conversation",
                question=question,
            )
            context.input_data["_prompt_version"] = "compliance_officer.qa.2026-02-25.1"

            # Call Claude
            response = await self.call_claude(prompt, context)

            return AgentResult(
                agent_type=self.agent_type,
                success=True,
                result={
                    "question": question,
                    "answer": response.get("answer", ""),
                    "confidence": response.get("confidence", "medium"),
                    "sources": response.get("sources", []),
                    "followup_questions": response.get("followup_questions", []),
                    "practical_implications": response.get("practical_implications", []),
                    "caveats": response.get("caveats", []),
                    "jurisdictional_notes": response.get("jurisdictional_notes", ""),
                },
                confidence=self.calculate_confidence(response),
                reasoning="Answered compliance question with regulatory citations",
            )

        except Exception as e:
            logger.error(f"Q&A error: {e}")
            return AgentResult(
                agent_type=self.agent_type,
                success=False,
                result=None,
                confidence=0.0,
                reasoning=f"Failed to answer question: {str(e)}",
                error=str(e),
            )

