@dataclass
class RiskIndicator:
    """A risk indicator or trend."""

    name: str
    current_value: float
    previous_value: float
    trend: str  # "up", "down", "stable"
    severity: str  # "critical", "warning", "normal"
    description: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "current_value": self.current_value,
            "previous_value": self.previous_value,
            "trend": self.trend,
            "severity": self.severity,
            "description": self.description,
            "change_percent": self._calculate_change(),
        }

    def _calculate_change(self) -> float:
        if self.previous_value == 0:
            return 100.0 if self.current_value > 0 else 0.0
        return ((self.current_value - self.previous_value) / self.previous_value) * 100


@dataclass
class ProactiveAlert:
    """A proactive alert generated by the AI."""

    alert_id: str
    priority: AlertPriority
    title: str
    description: str
    category: str
    recommended_action: str
    regulatory_reference: Optional[str] = None
    deadline: Optional[str] = None
    created_at: datetime = field(default_factory=datetime.utcnow)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "alert_id": self.alert_id,
            "priority": self.priority.value,
            "title": self.title,
            "description": self.description,
            "category": self.category,
            "recommended_action": self.recommended_action,
            "regulatory_reference": self.regulatory_reference,
            "deadline": self.deadline,
            "created_at": self.created_at.isoformat(),
        }


@dataclass
class DailyBriefing:
    """A daily compliance briefing."""

    briefing_id: str
    briefing_type: BriefingType
    generated_at: datetime
    period_start: datetime
    period_end: datetime

    # Executive summary
    executive_summary: str

    # Alert statistics
    total_alerts: int
    critical_alerts: int
    high_priority_alerts: int
    auto_resolved: int
    pending_review: int

    # Cases
    new_cases: int
    closed_cases: int
    escalated_cases: int

    # SARs
    sars_drafted: int
    sars_filed: int
    sars_pending: int

    # Risk indicators
    risk_indicators: List[RiskIndicator]

    # Proactive alerts
    proactive_alerts: List[ProactiveAlert]

    # Regulatory updates
    regulatory_updates: List[Dict[str, Any]]

    # Deadlines
    upcoming_deadlines: List[Dict[str, Any]]

    # Recommendations
    recommendations: List[str]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "briefing_id": self.briefing_id,
            "briefing_type": self.briefing_type.value,
            "generated_at": self.generated_at.isoformat(),
            "period_start": self.period_start.isoformat(),
            "period_end": self.period_end.isoformat(),
            "executive_summary": self.executive_summary,
            "alerts": {
                "total": self.total_alerts,
                "critical": self.critical_alerts,
                "high_priority": self.high_priority_alerts,
                "auto_resolved": self.auto_resolved,
                "pending_review": self.pending_review,
            },
            "cases": {
                "new": self.new_cases,
                "closed": self.closed_cases,
                "escalated": self.escalated_cases,
            },
            "sars": {
                "drafted": self.sars_drafted,
                "filed": self.sars_filed,
                "pending": self.sars_pending,
            },
            "risk_indicators": [ri.to_dict() for ri in self.risk_indicators],
            "proactive_alerts": [pa.to_dict() for pa in self.proactive_alerts],
            "regulatory_updates": self.regulatory_updates,
            "upcoming_deadlines": self.upcoming_deadlines,
            "recommendations": self.recommendations,
        }


